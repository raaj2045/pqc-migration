#!/usr/bin/env python3
"""Figure and table for the Ethereum -> Cosmos migration measurements.

    python3 experiments/migration_cost/plot_data.py

Reads everything under results/ and writes:

    fig_time_by_step.pdf          how long each step of a migration takes
    fig_throughput_by_workers.pdf transfers per second, as more relayers work at once
    cost_by_batch.md              gas per transfer on each leg, by batch size

Error bars and the ± in the table are 95% confidence intervals. How many runs
sit behind each step differs: waiting for finality and verifying in CosmWasm
happen once for a whole group of migrations, not once each. The counts are in
README.md rather than on the figure, where they only crowd the bars.
"""
import argparse
import csv
import glob
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"

# Every step of a round trip, in the order it happens.
STEPS = [
    ("T_Submit_s", "Escrow ERC-20\n(Ethereum)", "#2a78d6"),
    ("T_Wait_Finality_s", "Wait for finality\n(Ethereum)", "#eb6834"),
    ("T_Update_Client_s", "CosmWasm verification\n(Cosmos)", "#1baf7a"),
    # Minting also writes the acknowledgement: MsgRecvPacket mints the
    # ibc/<hash> voucher and writes the ack in the same transaction, which is
    # why the two SP1 steps below exist at all. The bar says "IBC token" rather
    # than "voucher" so it pairs with the ERC-20 it is escrowed against; the
    # README connects the two words.
    ("T_Deliver_s", "Mint IBC token\n(Cosmos)", "#4a3aa7"),
    # Generated by proof-api, not by either chain, so it costs no gas.
    ("T_Prove_Real_s", "SP1 proof generation\n(off-chain)", "#eda100"),
    ("T_Ack_Submit_s", "SP1 verification\n(Ethereum)", "#e87ba4"),
]

# Steps measured once for a whole group of migrations rather than once each.
# Counting rows would treat one measurement copied across a group as that many
# independent samples.
SHARED_STEPS = {"T_Wait_Finality_s", "T_Update_Client_s"}

# Steps measured by the return-leg runs rather than by a migration's own row.
ACK_STEPS = {"T_Ack_Submit_s"}

# The only steps the signing key can affect: the two Cosmos transactions the
# relayer signs. Submitting and acknowledging are Ethereum transactions, signed
# with secp256k1 either way; waiting for finality and generating the proof
# involve no signature at all. Those four are drawn as ONE bar over both sets of
# runs -- two coloured bars there would imply a difference that cannot exist,
# and the gas confirms it: submission is 166,001 in both arms to the gas unit.
KEY_DEPENDENT = {"T_Update_Client_s", "T_Deliver_s"}

# Real SP1 Groth16 proving, measured on the Cosmos -> Ethereum leg. It does not
# involve the delivery signing key, so it is one bar rather than two, and it is
# read from those result files rather than restated here.
REAL_PROVE_DIR = HERE.parent / "migration_throughput" / "results" / "real-verifier"

KEY_ORDER = ["secp256k1", "mldsa65"]
KEY_COLORS = {"secp256k1": "#1f77b4", "mldsa65": "#d62728"}
KEY_LABELS = {"secp256k1": "secp256k1 signer", "mldsa65": "ML-DSA-65 signer"}
KEY_MARKERS = {"secp256k1": "o", "mldsa65": "s"}

# Colour carries exactly one meaning on the step figure: which signing key. A
# step the key cannot affect is grey, so no reader looks for a comparison that
# is not there.
# Colour carries one meaning on the step figure: which key signs, and where.
# secp256k1 and ML-DSA-65 are the two Cosmos options being compared; the
# Ethereum steps are always secp256k1 because Ethereum accepts nothing else;
# waiting and proving involve no signature at all.
ETH_SIGNED = "#1baf7a"
UNSIGNED = "#6b7280"
# Which group each step belongs to.
STEP_GROUP = {
    "T_Submit_s": "eth", "T_Ack_Submit_s": "eth",
    "T_Wait_Finality_s": "none", "T_Prove_Real_s": "none",
}

plt.style.use("seaborn-v0_8-whitegrid")
plt.rcParams.update({
    "font.family": "serif", "font.size": 12, "axes.titlesize": 13,
    "axes.labelsize": 12, "legend.fontsize": 10, "figure.dpi": 150,
})


def mean_ci(values):
    """Mean and 95% confidence half-width. One sample has no interval, so it
    gets zero rather than a gap that would vanish silently from a figure."""
    v = np.asarray(list(values), dtype=float)
    if len(v) == 0:
        return float("nan"), 0.0
    if len(v) < 2:
        return v.mean(), 0.0
    return v.mean(), 1.96 * v.std(ddof=1) / np.sqrt(len(v))


def keys_present(df):
    return [k for k in KEY_ORDER if k in set(df["Signer_Key_Type"])] or \
        sorted(set(df["Signer_Key_Type"]))


def read_many(pattern):
    """Concatenate every results CSV matching a glob, or None if there are none."""
    files = sorted(glob.glob(str(RESULTS / pattern)))
    frames = [pd.read_csv(f) for f in files if Path(f).stat().st_size]
    return pd.concat(frames, ignore_index=True) if frames else None


def real_proving_seconds():
    out = []
    if not REAL_PROVE_DIR.exists():
        return out
    for f in sorted(REAL_PROVE_DIR.glob("*.json")):
        try:
            d = json.loads(f.read_text())
        except Exception:
            continue
        if "proveSeconds" in d:
            out.append(float(d["proveSeconds"]))
    return out


# --- how long each step takes -----------------------------------------------

def fig_time_by_step(df, out, batch=1, ack=None):
    """One bar per step, both signing keys side by side.

    The acknowledgement is measured by separate runs over the deliveries these
    ones produced, so it is matched by signing key and batch size rather than by
    individual run. Proving is the real SP1 Groth16 measurement; the mock
    verifier's proof check is a no-op and is not a cost worth plotting.
    """
    sub = df[df["N_Users"] == batch].copy()
    if sub.empty:
        print(f"skipping {out}: no rows at batch size {batch}")
        return
    keys = keys_present(sub)
    real_prove = real_proving_seconds()

    ack_by_key = {}
    if ack is not None:
        a = ack[ack["Batch_Size"] == batch]
        for k in keys:
            m = a[a["Signer_Key_Type"] == k]
            if len(m):
                ack_by_key[k] = {"T_Ack_Submit_s": m["T_Submit_s"].to_numpy()}

    fig, ax = plt.subplots(figsize=(12.5, 6))
    x = np.arange(len(STEPS))
    width = 0.8 / len(keys)

    def samples_for(col, kd, k, i):
        if col == "T_Prove_Real_s":
            return real_prove if i == 0 else []
        if col in ACK_STEPS:
            return ack_by_key.get(k, {}).get(col, [])
        if col in SHARED_STEPS and "Wave" in kd.columns:
            return kd.groupby("Wave")[col].first()
        return kd[col]

    for i, k in enumerate(keys):
        off = (i - (len(keys) - 1) / 2) * width
        means, cis, pos, widths, colors = [], [], [], [], []
        for j, (col, _, step_color) in enumerate(STEPS):
            if col in KEY_DEPENDENT:
                kd = sub[sub["Signer_Key_Type"] == k]
                samples = samples_for(col, kd, k, i)
                pos.append(x[j] + off); widths.append(width * 0.9)
                colors.append(KEY_COLORS.get(k, "#4a3aa7"))
            else:
                # One bar over every run, drawn once and centred.
                samples = samples_for(col, sub, k, i) if i == 0 else []
                if col in ACK_STEPS and i == 0:
                    samples = np.concatenate([v[col] for v in ack_by_key.values()]) \
                        if ack_by_key else []
                pos.append(x[j]); widths.append(width * 1.8)
                colors.append(ETH_SIGNED if STEP_GROUP.get(col) == "eth" else UNSIGNED)
            m, ci = mean_ci(samples)
            means.append(m); cis.append(ci)

        ax.bar(pos, means, widths, yerr=cis, capsize=3, color=colors,
               ecolor="#52514e", error_kw={"elinewidth": 1.2}, zorder=3)
        for xi, m, ci in zip(pos, means, cis):
            if m == m:
                ax.annotate(f"{m:,.1f}", (xi, m + ci), textcoords="offset points",
                            xytext=(0, 3), ha="center", fontsize=9,
                            fontweight="bold", color="#0b0b0b")

    # The finality wait and proving are a hundred times the small steps, so
    # a linear axis flattens the rest to nothing. Ticks stay plain numbers --
    # powers-of-ten notation makes a reader translate before they can read it.
    ax.set_yscale("log")
    ax.yaxis.set_major_formatter(matplotlib.ticker.ScalarFormatter())
    ax.yaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    # No title and no summary text: captions and totals belong in the paper,
    # where they can be written once and edited without regenerating a figure.
    ax.set_ylabel("Seconds (log scale)", fontweight="bold")
    ax.set_xlabel("Operation", fontweight="bold")
    ax.set_xticks(x, [lbl for _, lbl, _ in STEPS])
    ax.tick_params(axis="both", labelsize=10.5)
    ax.margins(y=0.3)

    from matplotlib.patches import Patch
    handles = [Patch(facecolor=KEY_COLORS.get(k, "#4a3aa7"),
                     label=f"Cosmos signer: {'secp256k1' if k == 'secp256k1' else 'ML-DSA-65'}")
               for k in keys]
    handles.append(Patch(facecolor=ETH_SIGNED, label="Ethereum signer: secp256k1"))
    handles.append(Patch(facecolor=UNSIGNED, label="no signature"))
    # A drawn error bar rather than a line of text, so the legend shows the
    # mark it is describing.
    handles.append(ax.errorbar([np.nan], [np.nan], yerr=[1], fmt="none",
                               ecolor="#52514e", elinewidth=1.4, capsize=4,
                               capthick=1.4, label="95% CI"))
    # Below the axes: with six bars and a three-line note there is no corner
    # inside the plot that does not cover a value.
    fig.legend(handles=handles, loc="lower center", ncol=4, frameon=False,
               bbox_to_anchor=(0.5, -0.04))
    fig.tight_layout(rect=(0, 0.09, 1, 1))
    fig.savefig(HERE / out, format="pdf", bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {out}")


# --- throughput against batch size ------------------------------------------

def fig_throughput_by_workers(tp, out):
    """How fast transfers arrive on Cosmos as more relayers work at once.

    One relayer is almost entirely idle waiting for Ethereum, so its rate says
    nothing about capacity. Capacity is what many relayers reach together, and
    the question is whether the signing key changes it.

    Timed span is delivery only. Waiting for finality is a fixed delay every
    transfer pays once, not a limit on the rate; the return leg needs a real
    proof at about ten minutes each. Both are in fig_time_by_step.pdf instead.
    """
    if tp is None:
        print(f"skipping {out}: no throughput results")
        return
    keys = keys_present(tp)
    counts = sorted(tp["Workers"].unique())

    fig, ax = plt.subplots(figsize=(8, 5.6))
    x = np.arange(len(counts))
    width = 0.8 / len(keys)
    for i, k in enumerate(keys):
        kd = tp[tp["Signer_Key_Type"] == k]
        off = (i - (len(keys) - 1) / 2) * width
        means, cis, pos = [], [], []
        for j, n in enumerate(counts):
            sel = kd[kd["Workers"] == n]["Transfers_Per_Second"]
            if not len(sel):
                continue
            m, ci = mean_ci(sel)
            means.append(m); cis.append(ci); pos.append(x[j] + off)
        ax.bar(pos, means, width * 0.9, yerr=cis, capsize=3,
               color=KEY_COLORS.get(k, "#4a3aa7"), ecolor="#52514e",
               error_kw={"elinewidth": 1.2},
               label=f"Cosmos signer: {'secp256k1' if k == 'secp256k1' else 'ML-DSA-65'}",
               zorder=3)
        # Above the error bar, not the bar top, or the cap sits on the number.
        for xi, m, ci in zip(pos, means, cis):
            ax.annotate(f"{m:,.1f}", (xi, m + ci), textcoords="offset points",
                        xytext=(0, 4), ha="center", fontsize=9.5,
                        fontweight="bold", color="#0b0b0b")

    ax.set_xlabel("Relayers", fontweight="bold")
    ax.set_ylabel("Migration requests processed / sec", fontweight="bold")
    ax.set_xticks(x, [str(n) for n in counts])
    ax.tick_params(axis="both", labelsize=10.5)
    # What the rate covers, and the interval convention, live in the README and
    # the paper caption rather than on the plot.
    handles, labels = ax.get_legend_handles_labels()
    handles.append(ax.errorbar([np.nan], [np.nan], yerr=[1], fmt="none",
                               ecolor="#52514e", elinewidth=1.4, capsize=4,
                               capthick=1.4, label="95% CI"))
    labels.append("95% CI")
    ax.legend(handles=handles, labels=labels, loc="upper left", frameon=True,
              framealpha=0.95, edgecolor="#d8d8d4")
    ax.margins(y=0.2)
    fig.tight_layout()
    fig.savefig(HERE / out, format="pdf", bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {out}")


# --- gas per transfer on each leg -------------------------------------------

def cost_by_batch(delivery, ack, out, ceiling=56):
    """A table, not a chart: the interesting quantity is the ratio between
    columns, which numbers carry better than bar heights."""
    if delivery is None:
        print(f"skipping {out}: no delivery results")
        return
    lines = [
        "# Gas per transfer, by how many move at once",
        "",
        "Delivery is Ethereum -> Cosmos, acknowledgement is Cosmos -> Ethereum.",
        "Each figure is gas for ONE transfer; ± is a 95% confidence interval and",
        "n is the number of runs behind it.",
        "",
    ]
    for k in keys_present(delivery):
        kd = delivery[delivery["Signer_Key_Type"] == k]
        ka = ack[ack["Signer_Key_Type"] == k] if ack is not None else None
        lines += [f"## {KEY_LABELS.get(k, k)}", "",
                  "| Transfers at once | Deliver on Cosmos | Acknowledge on Ethereum |",
                  "|---:|---:|---:|"]
        for n in sorted(kd["Batch_Size"].unique()):
            dm, dc = mean_ci(kd[kd["Batch_Size"] == n]["Deliver_Gas_Per_Tx"])
            dn = int((kd["Batch_Size"] == n).sum())
            cell_a = "—"
            if ka is not None and (ka["Batch_Size"] == n).any():
                am, ac = mean_ci(ka[ka["Batch_Size"] == n]["Ack_Gas_Per_Packet"])
                an = int((ka["Batch_Size"] == n).sum())
                cell_a = f"{am:,.0f} ± {ac:,.0f} (n={an})"
            elif n > ceiling:
                cell_a = f"over the {ceiling}-ack limit"
            lines.append(f"| {n} | {dm:,.0f} ± {dc:,.0f} (n={dn}) | {cell_a} |")
        lines.append("")

    lines += [
        "## Reading it",
        "",
        "Cost per transfer falls as more move together, because the costs charged",
        "once per transaction — the CosmWasm verification, the per-transaction",
        "overhead and the signature — are divided among more transfers. Both legs",
        f"flatten well before the {ceiling}-acknowledgement limit, so that limit",
        "costs nothing in gas; it only caps how many transfers one batch may hold.",
        "",
        "An acknowledgement batch is whatever one delivery produced, and the",
        f"multicall carrying it cannot be split, so delivering more than ~{ceiling}",
        "transfers at once leaves them impossible to acknowledge.",
        "",
    ]
    text = "\n".join(lines)
    (HERE / out).write_text(text)
    print(f"wrote {out}\n")
    print(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--batch", type=int, default=1,
                    help="batch size the per-step figure uses")
    args = ap.parse_args()

    delivery = read_many("delivery_*.csv")
    ack = read_many("ack_*.csv")
    if ack is not None:
        # The acknowledgement results record the signing key by name, not by
        # algorithm.
        ack["Signer_Key_Type"] = np.where(
            ack["Run_Label"].str.contains("relayer"), "mldsa65", "secp256k1")

    latency_path = RESULTS / "latency_by_step.csv"
    if latency_path.exists() and latency_path.stat().st_size:
        fig_time_by_step(pd.read_csv(latency_path), "fig_time_by_step.pdf",
                         args.batch, ack)
    else:
        print(f"skipping fig_time_by_step.pdf: no {latency_path.name}")

    fig_throughput_by_workers(read_many("throughput_*.csv"),
                              "fig_throughput_by_workers.pdf")

    cost_by_batch(delivery, ack, "cost_by_batch.md")


if __name__ == "__main__":
    main()
